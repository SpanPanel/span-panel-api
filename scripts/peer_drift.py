def render(found: Sequence[Producer]) -> str:
    return "\n".join(producer.section() for producer in found)


def exit_code(found: Sequence[Producer], *, strict: bool) -> int:
    """1 when a producer we depend on has moved past its pin, 0 when none has.

    Unknown is 0 unless `--strict`: a network this script could not reach is not
    evidence about a producer, and a commit is not the place to insist on one.
    Advisory producers count for neither — see `Producer.advisory`.
    """
    decisive = [producer for producer in found if not producer.advisory]
    if any(producer.verdict == "drift" for producer in decisive):
        return 1
    if strict and any(producer.verdict == "unknown" for producer in decisive):
        return 1
    return 0


def main(
    argv: Sequence[str] | None = None,
    *,
    get: HttpGet = http_get,
    ls: LsRemote = ls_remote,
    out: TextIO | None = None,
) -> int:
    parser = argparse.ArgumentParser(
        prog="peer_drift.py",
        description="Ask each producer pinned in spec_lock.json whether it has moved past the pin.",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="fail when a producer could not be asked, not only when one has drifted (CI passes this)",
    )
    parser.add_argument(
        "--peer",
        choices=sorted(BUILDERS),
        help="ask one producer instead of all of them",
    )
    namespace = parser.parse_args(argv)
    strict = bool(namespace.strict)
    only = None if namespace.peer is None else str(namespace.peer)

    lock = load()
    missing = unasked(lock)
    if missing:
        raise SystemExit(
            f"{LOCK.name} pins {', '.join(missing)}, which this script has no way to ask. "
            "Add a builder to scripts/peer_drift.py: a producer nobody asks about is a "
            "producer that moves unnoticed, which is the whole thing this check exists to stop."
        )
    unplaced = unvendored(lock)
    if unplaced:
        raise SystemExit(
            f"peers.{PANELBENCH}.fixtures names a {', '.join(unplaced)} capture and "
            "scripts/peer_drift.py records no path in this repository it is copied to. "
            "Add it to VENDORED, or a drift report will name the file and not what to do about it."
        )

    asked = [name for name in (PANELBENCH, PANEL_SIM, SPECIFICATION) if only is None or name == only]
    found = [BUILDERS[name](lock, get, ls) for name in asked]
    print(render(found), end="", file=sys.stdout if out is None else out)
    return exit_code(found, strict=strict)


if __name__ == "__main__":
    raise SystemExit(main())
