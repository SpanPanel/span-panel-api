def emitter(lock: Mapping[str, object], get: HttpGet, ls: LsRemote) -> Producer:
    """The released distribution the reference tree was captured from.

    The release is the verdict and the branch is context, because the capture
    script gates on a release: it refuses to write a tree taken from any version
    other than the pinned one, so unreleased commits cannot produce a capture we
    would accept even if we wanted one.
    """
    peer = pinned_peer(PANEL_SIM, lock)
    distribution = string(peer, "distribution", f"peers.{PANEL_SIM}")
    pinned = string(peer, "version", f"peers.{PANEL_SIM}")
    context = _emitter_commits(peer, ls)
    who = f"PyPI for {distribution}"

    try:
        index = _index(get(f"{PYPI_JSON}/{urllib.parse.quote(distribution)}/json"), pinned, who)
    except Unreachable as error:
        return Producer(PANEL_SIM, pinned, "", "unknown", f"{_unknown(who, error)}\n\n{context}")

    verdict, detail = _release_reading(peer, pinned, index)
    return Producer(PANEL_SIM, pinned, index.latest, verdict, f"{detail}\n\n{context}")


def _index(body: str, pinned: str, who: str) -> Index:
    """PyPI's answer, read once for both questions we ask of it."""
    answer = _answer(body, who)
    latest = _field(_member(answer, "info", who), "version", who)
    listed = _member(answer, "releases", who).get(pinned)
    if listed is None:
        return Index(latest, None, pinned_yanked=False)
    files = _objects(listed, f"releases.{pinned}", who)
    return Index(latest, len(files), pinned_yanked=bool(files) and all(entry.get("yanked") is True for entry in files))


def _release_reading(peer: Mapping[str, object], pinned: str, index: Index) -> tuple[Verdict, str]:
    """The verdict on the pinned release, and what to say about it.

    Only one branch here is drift, and it is the narrow one: a release that
    exists, is not withdrawn, and is genuinely later than ours. Everything else
    the index can say — a pin it does not serve, a pin it has yanked, a `latest`
    that is older or that carries a suffix this cannot order — is a disagreement
    we have no safe instruction for, so it is reported and not acted on.
    """
    problem = pin_problem(index, pinned)
    if problem is not None:
        return "unknown", _inconclusive(*problem)
    if index.latest == pinned:
        return "current", f"Latest release is `{index.latest}`, which is what we pin. The reference tree is current."

    newer = newer_release(index.latest, pinned)
    if newer is None:
        return "unknown", _inconclusive(
            f"PyPI's latest (`{index.latest}`) cannot be ordered against the pin (`{pinned}`)",
            "One of them carries a pre-release, post-release or local suffix. Ordering dotted "
            "integers is what the standard library gives us, and guessing at the rest would make "
            "a verdict out of a guess — read the emitter's releases and move the pin by hand.",
        )
    if not newer:
        return "unknown", _inconclusive(
            f"PyPI's latest (`{index.latest}`) is not newer than the pin (`{pinned}`)",
            "The index serves an older release than the one we pin — a newer release withdrawn "
            "after we pinned it, or an index that has not caught up. Re-capturing would take the "
            "reference tree backwards, which is why this is not reported as drift.",
        )
    return "drift", _emitter_drift(peer, pinned, index.latest)


def _emitter_drift(peer: Mapping[str, object], pinned: str, latest: str) -> str:
    """What to do about a reference tree captured from a superseded release."""
    capture = string(peer, "capture_script", f"peers.{PANEL_SIM}")
    produces = mapping(required(peer, "produces", f"peers.{PANEL_SIM}"), f"peers.{PANEL_SIM}.produces")
    tree = str(required(produces, "tree", f"peers.{PANEL_SIM}.produces"))
    return (
        f"Latest release is `{latest}`, we pin `{pinned}`.\n\n"
        "The reference tree was captured from the pinned release, so it now describes a\n"
        "producer that has been superseded. To follow:\n\n"
        "```bash\n"
        f"# in a checkout of the emitter at {released_tag(peer, latest)}, from its own environment\n"
        f"uv run python ../{REPO.name}/{capture} \\\n"
        f"  ../{REPO.name}/{tree}\n"
        "```\n\n"
        f"The script refuses until `peers.{PANEL_SIM}.version` and `.commit` in\n"
        f"`{LOCK.name}` name the release you captured from, which is what keeps the\n"
        "bytes and the claim about them from drifting apart. Read the emitter's CHANGELOG\n"
        "for the wire changes before accepting the new capture: a diff confined to each\n"
        "`$description`'s `version` means nothing moved."
    )


def _emitter_commits(peer: Mapping[str, object], ls: LsRemote) -> str:
    """Where the emitter's branch is, which is context and says so."""
    repo = string(peer, "repo", f"peers.{PANEL_SIM}")
    ref = string(peer, "ref", f"peers.{PANEL_SIM}")
    commit = string(peer, "commit", f"peers.{PANEL_SIM}")
    heading = f"### {slug(repo)} commits"
    try:
        head = ls(repo, f"refs/heads/{ref}")
    except Unreachable as error:
        return f"{heading}\n\nCould not ask where `{ref}` is (`{error}`)."
    if head == commit:
        return f"{heading}\n\n`{ref}` is at `{short(commit)}`, the commit we pin."
    return (
        f"{heading}\n\n"
        f"`{ref}` is at `{short(head)}`, we pin `{short(commit)}` — the branch head has\n"
        "moved past the pin. Unreleased work, so not itself a reason to recapture; the\n"
        "release comparison above is. How many commits, and which, needs a clone — the\n"
        "scheduled `peer-drift.yml` run has one and lists them."
    )


def panelbench(lock: Mapping[str, object], get: HttpGet, ls: LsRemote) -> Producer:
    """The repository whose captures are byte-copied here.

    Two questions, cheapest first. `git ls-remote` says whether the branch has
    moved at all, and on the ordinary day — the pin at the branch head — that is
    the whole answer and no API request is made. Only a branch that has moved is
    worth spending a compare on, and only then does *what* it changed matter.
    """
    peer = pinned_peer(PANELBENCH, lock)
    repo = string(peer, "repo", f"peers.{PANELBENCH}")
    ref = string(peer, "ref", f"peers.{PANELBENCH}")
    commit = string(peer, "commit", f"peers.{PANELBENCH}")
    name = slug(repo)
    who = f"GitHub what {name} changed"

    try:
        head = ls(repo, f"refs/heads/{ref}")
    except Unreachable as error:
        return Producer(PANELBENCH, commit, "", "unknown", _unknown(f"{name} where `{ref}` is", error))
    if head == commit:
        return Producer(
            PANELBENCH,
            commit,
            head,
            "current",
            f"`{ref}` is at `{short(commit)}`, the commit we pin. Nothing to re-vendor.",
        )

    try:
        # Against the commit `ls-remote` just resolved, not against the branch
        # name: the branch could move between the two calls, and a summary that
        # names one commit while comparing another is two facts pretending to be
        # one.
        comparison = compare(repo, commit, head, get, who)
    except Unreachable as error:
        return Producer(PANELBENCH, commit, head, "unknown", _unknown(who, error))

    moved = f"`{ref}` is at `{short(head)}`, we pin `{short(commit)}`"
    verdict, detail = _panelbench_reading(comparison, moved, watched(peer), fixtures(peer))
    return Producer(PANELBENCH, commit, head, verdict, detail)


def _panelbench_reading(
    comparison: Comparison, moved: str, watch: Sequence[str], sources: Mapping[str, str]
) -> tuple[Verdict, str]:
    """What the comparison means, once it has been obtained."""
    if comparison.behind_by:
        detail = (
            f"**UNKNOWN — {moved}, and the pin is not an ancestor of it.**\n\n"
            "The pin names a commit this branch does not contain — a branch that was\n"
            f"rebased, squash-merged or deleted. `peers.{PANELBENCH}.ref` in `{LOCK.name}`\n"
            "needs to name a ref the pinned commit is actually on, and until it does\n"
            "nothing here can say whether what we vendor is current."
        )
        return "unknown", detail

    changed = touched(comparison.files, watch)
    if not changed and comparison.capped:
        # Asked in this order because a file we vendor appearing in a truncated
        # list is still a file we vendor having changed. Only the *absence* of one
        # is unsafe to conclude from a list the API cut short.
        detail = (
            f"**UNKNOWN — {moved}, {comparison.ahead_by} commits ahead, and the comparison\n"
            f"named {COMPARE_FILE_LIMIT} changed files, which is all the API will list.**\n\n"
            'A truncated list cannot be read as "nothing we vendor changed", because the\n'
            "file that did may be one it declined to name. Compare against a checkout — the\n"
            "byte comparison in `tests/test_schema_one_conformance.py` is the answer that\n"
            "does not truncate."
        )
        return "unknown", detail

    if not changed:
        detail = (
            f"{moved} — {comparison.ahead_by} commits ahead, nothing we copy changed.\n\n"
            "Green deliberately: this repository vendors two captures and reads one\n"
            "lockfile out of that branch, and a commit touching none of them is the\n"
            "producer's business rather than ours."
        )
        return "current", detail

    return "drift", _panelbench_drift(moved, comparison, changed, sources)


def _panelbench_drift(moved: str, comparison: Comparison, changed: Sequence[str], sources: Mapping[str, str]) -> str:
    """What to do about a producer that changed something we keep a copy of."""
    lines = [
        f"**{moved} — {comparison.ahead_by} commits ahead, and it changed what we vendor:**",
        "",
        *(f"- `{path}`" for path in changed),
        "",
    ]
    captures = sorted((source, VENDORED[kind]) for kind, source in sources.items() if source in changed)
    if captures:
        lines += [
            "Re-vendor and re-pin together, in one change:",
            "",
            "```bash",
            *(f"cp $PANELBENCH_DIR/{source} \\\n   {destination}" for source, destination in captures),
            "```",
            "",
            f"then set `peers.{PANELBENCH}.commit` in `{LOCK.relative_to(REPO)}` to the",
            "commit you copied from. A capture without a commit bump records where the bytes",
            "came from as a guess.",
            "",
        ]
    if EBUS_SPEC_FILE in changed:
        lines += [
            f"`{EBUS_SPEC_FILE}` is the producer's own record of the specification commit it",
            f"implements. The two sides are reading different vocabularies until `peers.{PANELBENCH}`'s",
            "`synced_commit` and the vendored catalogs move together.",
            "",
        ]
    lines += [
        "The byte comparison in `tests/test_schema_one_conformance.py` is what settles it,",
        "and it is the same one `ci.yml` runs — this only says the producer moved first.",
    ]
    return "\n".join(lines)


def compare(repo: str, base: str, head: str, get: HttpGet, who: str) -> Comparison:
    """`base...head`, as GitHub answers it, needing no clone of either."""
    url = f"{GITHUB_API}/repos/{slug(repo)}/compare/{urllib.parse.quote(base)}...{urllib.parse.quote(head)}"
    answer = _answer(get(url), who)
    return Comparison(
        ahead_by=_count(answer, "ahead_by", who),
        behind_by=_count(answer, "behind_by", who),
        files=_filenames(answer, who),
    )


def specification(lock: Mapping[str, object], ls: LsRemote) -> Producer:
    """The document both producers implement. Context, never a verdict.

    A specification that has moved does not make anything here wrong: it says
    what a device class *may* publish, and what this repository vendors out of it
    is byte-compared against `synced_commit` by `ci.yml`. Reported so that a
    disagreement with a producer can be read against the right revision of the
    document, and marked advisory so it can never fail a commit.
    """
    repo = string(lock, "spec_repo", LOCK.name)
    pinned = string(lock, "synced_commit", LOCK.name)
    name = slug(repo)
    try:
        head = ls(repo, "HEAD")
    except Unreachable as error:
        return Producer(SPECIFICATION, pinned, "", "unknown", _unknown(f"{name} where HEAD is", error), advisory=True)
    if head == pinned:
        return Producer(
            SPECIFICATION,
            pinned,
            head,
            "current",
            f"`{name}` is at `{short(head)}`, the commit we sync to.",
            advisory=True,
        )
    detail = (
        f"`{name}` is at `{short(head)}`, we sync to `{short(pinned)}`.\n\n"
        "Context, not a verdict, and it fails nothing. The specification says what a device\n"
        "class may publish rather than what one does, and the catalogs vendored from it are\n"
        "byte-compared against the pinned commit by `ci.yml`. Worth reading when a producer\n"
        "and this parser disagree — the two sides may be reading different revisions of it."
    )
    return Producer(SPECIFICATION, pinned, head, "drift", detail, advisory=True)


BUILDERS: dict[str, Callable[[Mapping[str, object], HttpGet, LsRemote], Producer]] = {
    PANELBENCH: panelbench,
    PANEL_SIM: emitter,
    SPECIFICATION: lambda lock, get, ls: specification(lock, ls),
}
"""One builder per producer, because they are not the same shape. Keyed by the
name the lockfile uses, so `--peer` names what `spec_lock.json` names."""


