GITHUB_API = "https://api.github.com"
PYPI_JSON = "https://pypi.org/pypi"

Verdict = Literal["current", "drift", "unknown"]


class Unreachable(Exception):
    """A producer could not be asked.

    Deliberately not an answer. Every caller turns this into `unknown` and says
    so in the summary, because the alternative — treating silence as agreement —
    is how a check reports green on the day it had nothing to report at all.
    """


class HttpGet(Protocol):
    """Fetch a URL, or raise `Unreachable`. Injected so tests never leave the machine."""

    def __call__(self, url: str) -> str: ...


class LsRemote(Protocol):
    """Resolve a ref in a remote repository to a commit, or raise `Unreachable`."""

    def __call__(self, repo: str, ref: str) -> str: ...


@dataclass(frozen=True)
class Producer:
    """One producer, asked and answered.

    `pinned` and `observed` are the same fact as `detail`, in the currency the
    comparison was made in — a release for the emitter, a commit for the other
    two. The prose is what a person reads in a job summary; these are what a test
    can assert on without matching sentences.
    """

    name: str
    pinned: str
    observed: str
    verdict: Verdict
    detail: str
    advisory: bool = False
    """Reported, never counted. Set for the specification, whose movement is
    context for reading a disagreement rather than a reason to change anything
    here, and so must not fail a commit or a job."""

    def section(self) -> str:
        return f"## {self.name}\n\n{self.detail.rstrip()}\n"


@dataclass(frozen=True)
class Comparison:
    """GitHub's answer to `compare/<base>...<head>`, narrowed to what we read.

    `behind_by` rather than the API's own `status` word: what we need to know is
    whether the pin is an ancestor of the branch, and a non-zero count of commits
    the base has and the head does not is exactly that question answered.
    """

    ahead_by: int
    behind_by: int
    files: tuple[str, ...]

    @property
    def capped(self) -> bool:
        return len(self.files) >= COMPARE_FILE_LIMIT


@dataclass(frozen=True)
class Index:
    """What PyPI says about a distribution, narrowed to the two things we ask.

    `latest` alone was not enough. It answers "is there something newer?" only if
    the pin is still a release PyPI serves, and it is not the same question as
    "is what we pinned still installable" — a yanked or withdrawn release leaves
    `latest` looking perfectly ordinary while the reference tree describes
    something nobody can get.
    """

    latest: str
    pinned_files: int | None
    """How many files the index lists for the pinned release; `None` when it does
    not list that release at all."""
    pinned_yanked: bool
    """Every file of the pinned release withdrawn. PyPI yanks per file, so this
    is the whole release only when they all carry the flag."""


# ---------------------------------------------------------------------------
# Asking, over the network
# ---------------------------------------------------------------------------


def _headers(url: str) -> dict[str, str]:
    """Authenticate to the GitHub API when a token is around, and nowhere else.

    CI has one and wants the higher rate limit; a developer machine usually does
    not, and 60 unauthenticated requests an hour is ample for a hook that makes
    at most one such request per commit. The host check is not decoration: a
    credential sent to a service that did not ask for it is a credential
    disclosed, and PyPI has no use for a GitHub token.
    """
    if not url.startswith(GITHUB_API):
        return {}
    headers = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN") or ""
    if token:
        headers["Authorization"] = f"Bearer {token}"
    return headers


def http_get(url: str) -> str:
    request = urllib.request.Request(url, headers=_headers(url))
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT) as response:
            body: bytes = response.read()
    except urllib.error.HTTPError as error:
        if error.code in (403, 429) and error.headers.get("x-ratelimit-remaining") == "0":
            raise Unreachable(
                "GitHub's rate limit is spent; set GH_TOKEN to raise it from the unauthenticated 60/hr"
            ) from error
        raise Unreachable(f"HTTP {error.code} {error.reason}") from error
    except (urllib.error.URLError, TimeoutError, OSError) as error:
        raise Unreachable(str(error)) from error
    return body.decode("utf-8", errors="replace")


def ls_remote(repo: str, ref: str) -> str:
    """The commit a remote ref names, without cloning anything.

    `GIT_TERMINAL_PROMPT=0` because this runs in a pre-commit hook: a repository
    that has gone private must report as unreachable rather than stop a commit at
    a password prompt nobody is watching for.
    """
    environment = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    try:
        completed = subprocess.run(
            ["git", "ls-remote", repo, ref],
            capture_output=True,
            text=True,
            timeout=TIMEOUT,
            check=False,
            env=environment,
        )
    except subprocess.TimeoutExpired as error:
        raise Unreachable(f"git ls-remote did not answer within {TIMEOUT:.0f}s") from error
    except OSError as error:
        raise Unreachable(str(error)) from error
    if completed.returncode != 0:
        detail = completed.stderr.strip().splitlines()
        raise Unreachable(detail[-1] if detail else f"git ls-remote exited {completed.returncode}")
    fields = completed.stdout.split()
    if not fields:
        raise Unreachable(f"{repo} has no {ref}")
    return fields[0]


# ---------------------------------------------------------------------------
# Reading what came back, which is somebody else's JSON
# ---------------------------------------------------------------------------


def _answer(body: str, who: str) -> dict[str, object]:
    try:
        loaded: object = json.loads(body)
    except json.JSONDecodeError as error:
        raise Unreachable(f"{who} did not answer with JSON ({error})") from error
    if not isinstance(loaded, Mapping):
        raise Unreachable(f"{who} answered with {type(loaded).__name__}, not an object")
    return {str(key): value for key, value in loaded.items()}


def _member(source: Mapping[str, object], key: str, who: str) -> dict[str, object]:
    value = source.get(key)
    if not isinstance(value, Mapping):
        raise Unreachable(f"{who} answered with no {key!r} object")
    return {str(inner): item for inner, item in value.items()}


def _field(source: Mapping[str, object], key: str, who: str) -> str:
    value = source.get(key)
    if not isinstance(value, str):
        raise Unreachable(f"{who} answered with no {key!r} string")
    return value


def _count(source: Mapping[str, object], key: str, who: str) -> int:
    value = source.get(key)
    if isinstance(value, bool) or not isinstance(value, int):
        raise Unreachable(f"{who} answered with no {key!r} count")
    return value


def _objects(listed: object, key: str, who: str) -> list[dict[str, object]]:
    """A list of JSON objects, which is the shape both producers answer files in."""
    if not isinstance(listed, Sequence) or isinstance(listed, str | bytes):
        raise Unreachable(f"{who} answered with a {key!r} that is not a list")
    entries: list[dict[str, object]] = []
    for entry in listed:
        if not isinstance(entry, Mapping):
            raise Unreachable(f"{who} answered with a {key!r} entry that is not an object")
        entries.append({str(inner): value for inner, value in entry.items()})
    return entries


def _filenames(source: Mapping[str, object], who: str) -> tuple[str, ...]:
    """The changed files, which the API omits entirely when there are none."""
    return tuple(_field(entry, "filename", who) for entry in _objects(source.get("files", []), "files", who))


