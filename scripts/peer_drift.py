"""Has a producer moved past the pin?

`spec_lock.json` records three producers this repository copies from or is
generated by: the eBus **specification**, whose capability catalogs are vendored
under `packages/schema-1/spec/`; **panelbench**, whose captures are byte-copied
into that same directory; and the **eBus emitter**, a released distribution that
produced the reference tree twenty test modules replay. Any of them can move
without a file here being touched, and when one does the pin stops describing a
producer and starts describing a moment.

The provenance tests answer the other half of the question — do our bytes still
match the commit we claim they came from — and they answer it against sibling
checkouts, which says nothing about what a producer has *published* since. This
asks the producers themselves, over the network and with no checkout at all:
PyPI for the emitter's latest release, GitHub's compare API for what panelbench
changed, `git ls-remote` for where a branch is.

It is a script rather than a workflow step because it runs in two places.
`.github/workflows/peer-drift.yml` runs it daily under `--strict`, which is the
backstop. `.pre-commit-config.yaml` runs it on every commit, which is where it is
meant to catch things: the drift this exists to prevent was a producer release
that nobody here noticed until a scheduled job went red, and a check only CI runs
is a check that finds out late.

**A verdict, or context.** Two comparisons are verdicts, and both are verdicts
about bytes in this repository having gone stale:

- the emitter's *release*, because the reference tree is a capture of one and
  `capture_parent_child_reference.py` refuses to write a capture from any other
  version. Commits on the emitter's branch are unreleased work, reported because
  they are what a release will be made of, never a call to action.
- a panelbench commit that touches a file we vendor. Commits that touch nothing
  we copy are reported and stay green: a README commit there is not a defect
  here.

The specification is context only and never a verdict. It says what a device
class *may* publish, the vendored catalogs are byte-compared against
`synced_commit` by `ci.yml`, and a specification that has moved is something to
read rather than something to fix.

**Not having asked is not the same fact as there being nothing new.** A producer
that could not be reached is reported as UNKNOWN, loudly, and exits 0 — a laptop
on a plane still has to be able to commit. `--strict` turns unknown into a
failure, because in CI there is no such excuse.

Nothing here restates a pin, a path or a repository. Every one of them is read
from `spec_lock.json`, which is their single home; a constant in this file would
be a second one, agreeing right up until the day somebody moved only one.
"""

